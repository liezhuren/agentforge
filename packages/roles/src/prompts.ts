/**
 * 五角色 system prompt。
 *
 * 主理人的 prompt 是整套设计里最需要小心的一段（docs/03 §1）：
 * 光说「你必须挑错」会驱动奖励黑客 —— 模型的最优策略变成「产出看起来像问题的东西」。
 * 所以这里做了两件事：
 *   1. **改变目标函数**：明说你的评分是 precision，不是异议数量
 *   2. **给「同意」留一个不亏的出口**：明说输出 NO_OBJECTION 是正确答案且不受惩罚
 *
 * 第 2 点尤其重要。如果「同意」被隐性惩罚，模型在压力下**一定会**编造问题 ——
 * 这不是模型坏，是激励坏。
 */

